// live(Ollama) 경로 확인: 같은 데모 흐름을 실제 로컬 모델로 한 번 돌리고 걸린 시간·출처 표시를 남긴다.
// 사용: PORT=8788 AI_MODE=live 서버를 띄운 뒤 BASE_URL=http://localhost:8788 node e2e/live-ollama.mjs
import { chromium } from 'playwright';
const BASE = process.env.BASE_URL ?? 'http://localhost:8788';
const OUT = process.env.SHOT_DIR ?? 'screenshots';
const browser = await chromium.launch();
const t = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
t.on('dialog', (d) => d.accept());
const api = t.request;
await api.post(`${BASE}/api/demo/reset`);
await t.goto(`${BASE}/`);
await t.selectOption('[data-testid=unit-A]', '우리가 사는 곳 - 더 살기 좋은 곳 만들기');
await t.selectOption('[data-testid=unit-B]', '지도로 만나는 우리 지역 - 지도에서 우리 지역 찾기');
let t0 = Date.now();
await t.getByTestId('generate').click();
await t.getByTestId('flow-log').getByText('✓ 계획').waitFor({ timeout: 120000 });
await t.screenshot({ path: `${OUT}/live-01-S1-progress.png` });
await t.getByTestId('repair-summary').waitFor({ timeout: 240000 });
await t.getByTestId('flow-log').getByText('✓ 수리').or(t.getByTestId('flow-log').getByText('! 수리')).waitFor({ timeout: 240000 });
console.log('lesson ms', Date.now() - t0, '|', await t.getByTestId('repair-summary').innerText());
console.log('sources', (await t.getByTestId('repair-log').innerText()).split('\n').filter((l) => l.includes('AI 경로') || l.includes('걸린')).join(' / '));
await t.evaluate(() => scrollTo(0, 0));
await t.screenshot({ path: `${OUT}/live-02-S1-done.png`, fullPage: true });
await t.getByRole('link', { name: '질문함' }).click();
await t.getByTestId('start-session').click();
const code = (await t.getByTestId('session-code').innerText()).trim();
await api.post(`${BASE}/api/sessions/${code}/fake-students?fast=1`);
await t.waitForFunction(() => document.querySelectorAll('[data-testid=response-card]').length >= 12, null, { timeout: 30000 });
t0 = Date.now();
await t.getByTestId('cluster').click();
await t.getByTestId('cluster-card').first().waitFor({ timeout: 180000 });
console.log('cluster ms', Date.now() - t0, 'clusters', await t.getByTestId('cluster-card').count());
await t.evaluate(() => scrollTo(0, 0));
await t.screenshot({ path: `${OUT}/live-03-S3-clusters.png`, fullPage: true });
await t.getByTestId('go-next').click();
t0 = Date.now();
await t.getByTestId('gen-cards').click();
await t.getByTestId('card-A-보충').waitFor({ timeout: 180000 });
console.log('cards ms', Date.now() - t0);
await t.evaluate(() => scrollTo(0, 0));
await t.screenshot({ path: `${OUT}/live-04-S4-cards.png`, fullPage: true });
const st = await (await api.get(`${BASE}/api/ai/status`)).json();
console.log('status', JSON.stringify(st));
await browser.close();
